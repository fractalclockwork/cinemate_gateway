"""Export software/keymap.yaml → CircuitPython keymap_gen.py for the Pico."""

from __future__ import annotations

import argparse
from pathlib import Path

from software.hid import resolve_action
from software.keymap import ACTIVE, EXAMPLE, load_keymap

REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUT = REPO_ROOT / "hardware" / "firmware" / "pico" / "keymap_gen.py"


def parse_frame_key(ir_key: str) -> tuple[str, int, int, int | None]:
    parts = str(ir_key).split(":")
    if len(parts) == 3:
        proto, addr_s, cmd_s = parts
        return proto, int(addr_s, 16), int(cmd_s, 16), None
    if len(parts) == 4:
        proto, addr_s, cmd_s, ext_s = parts
        return proto, int(addr_s, 16), int(cmd_s, 16), int(ext_s, 16)
    raise ValueError(f"bad IR key {ir_key!r}; expected proto:aa:cc or proto:aa:cc:ee")


def keymap_entries(keymap: dict | None = None) -> list[tuple[tuple, tuple[str, str]]]:
    data = keymap if keymap is not None else load_keymap()
    entries: list[tuple[tuple, tuple[str, str]]] = []
    for ir_key, action_name in data["map"].items():
        action = resolve_action(str(action_name))
        proto, address, command, extended = parse_frame_key(str(ir_key))
        if proto.startswith("sony-sirc") and extended is not None:
            key = (address, command, extended)
        elif proto.startswith("sony-sirc"):
            key = (address, command)
        elif proto == "nec-like":
            key = (address, command)
        else:
            raise ValueError(f"unsupported protocol in firmware export: {proto}")
        entries.append((key, (action.kind, action.usage_name)))
    return entries


def _fmt_tuple_key(key: tuple) -> str:
    return "(" + ", ".join(f"0x{int(part):02x}" for part in key) + ")"


def render_keymap_gen(entries: list[tuple[tuple, tuple[str, str]]], source: Path) -> str:
    try:
        rel = source.resolve().relative_to(REPO_ROOT)
        source_shown = rel.as_posix()
    except ValueError:
        source_shown = source.as_posix()
    lines = [
        "# Autogenerated by software.export_firmware_keymap — do not edit by hand.",
        f"# Source: {source_shown}",
        "# KEYMAP keys: (address, command) or (address, command, extended) for SIRC-20.",
        "KEYMAP = {",
    ]
    for key, (kind, name) in entries:
        lines.append(f"    {_fmt_tuple_key(key)}: ({kind!r}, {name!r}),")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def write_keymap_gen(
    out: Path = DEFAULT_OUT,
    keymap_path: Path | None = None,
) -> Path:
    path = keymap_path or (ACTIVE if ACTIVE.is_file() else EXAMPLE)
    data = load_keymap(path)
    entries = keymap_entries(data)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render_keymap_gen(entries, path))
    return out


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description="Export host keymap to CircuitPython")
    parser.add_argument(
        "--keymap",
        type=Path,
        default=None,
        help="host keymap YAML (default: software/keymap.yaml)",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=DEFAULT_OUT,
        help="output keymap_gen.py path",
    )
    args = parser.parse_args(argv)
    path = write_keymap_gen(out=args.out, keymap_path=args.keymap)
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
