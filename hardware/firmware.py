"""Flash / deploy CircuitPython app after operator verification and a present pass."""

from __future__ import annotations

import argparse
import hashlib
import os
import re
import shutil
import subprocess
import time
from pathlib import Path

from hardware.loopback import parse_digest_from_banner, soft_reset_pico
from hardware.records import load_board, stage_passed
from hardware import probe
from operator import assent

FIRMWARE_SRC = Path(__file__).resolve().parent / "firmware" / "pico"
ADAFRUIT_HID_REL = Path("lib") / "adafruit_hid"
DIGEST_FILES = ("boot.py", "code.py", "keymap_gen.py")
STAMP_NAME = "deploy_stamp.py"
# Host/desktop litter on CIRCUITPY triggers CircuitPython auto-reload storms.
CIRCUITPY_JUNK = (
    ".Trash-1000",
    ".Trashes",
    ".fseventsd",
    ".Spotlights-V100",
    ".TemporaryItems",
    "._.Trashes",
)


def adafruit_hid_present(root: Path) -> bool:
    hid_dir = root / ADAFRUIT_HID_REL
    marker = hid_dir / "__init__.py"
    return hid_dir.is_dir() and (marker.is_file() or any(hid_dir.glob("*.mpy")))


def require_adafruit_hid(root: Path) -> None:
    """Fail deploy when CIRCUITPY (or sim dest) lacks adafruit_hid after copy."""
    if adafruit_hid_present(root):
        return
    raise SystemExit(
        "adafruit_hid missing under "
        f"{root / ADAFRUIT_HID_REL}. "
        "Vendor copy belongs at hardware/firmware/pico/lib/adafruit_hid/ "
        "(see that folder's VENDOR.md). Deploy refuses a non-bootable tree."
    )


def firmware_tree_digest(root: Path) -> str:
    """Short sha256 over boot/code/keymap — the running app identity."""
    hasher = hashlib.sha256()
    for name in DIGEST_FILES:
        path = root / name
        if not path.is_file():
            raise FileNotFoundError(f"missing {path} for firmware digest")
        hasher.update(name.encode())
        hasher.update(b"\0")
        hasher.update(path.read_bytes())
        hasher.update(b"\0")
    return hasher.hexdigest()[:12]


def render_deploy_stamp(digest: str) -> str:
    return (
        "# Generated by hardware.firmware before each deploy — do not edit by hand.\n"
        f'DIGEST = "{digest}"\n'
    )


def write_deploy_stamp(root: Path, digest: str) -> Path:
    path = root / STAMP_NAME
    path.write_text(render_deploy_stamp(digest))
    return path


def read_stamp_digest(root: Path) -> str | None:
    path = root / STAMP_NAME
    if not path.is_file():
        return None
    match = re.search(r'DIGEST\s*=\s*"([0-9a-f]+|unset)"', path.read_text())
    return match.group(1) if match else None


def verify_running_digest(*, expected: str, banner: str, mount: Path | None) -> None:
    """Fail loudly if the live DUT is not running the digest we just deployed."""
    live = parse_digest_from_banner(banner)
    if live != expected:
        raise SystemExit(
            f"firmware digest mismatch on serial: want {expected}, got {live!r}. "
            f"banner={banner!r}. Unplug/replug once, then re-run make firmware."
        )
    if mount is not None:
        stamped = read_stamp_digest(mount)
        if stamped != expected:
            raise SystemExit(
                f"firmware digest mismatch on CIRCUITPY/{STAMP_NAME}: "
                f"want {expected}, got {stamped!r}."
            )
        # Remounted tree must match the digest inputs too.
        try:
            mounted_digest = firmware_tree_digest(mount)
        except FileNotFoundError as exc:
            raise SystemExit(f"CIRCUITPY incomplete after deploy: {exc}") from exc
        if mounted_digest != expected:
            raise SystemExit(
                f"CIRCUITPY tree digest {mounted_digest} != deployed {expected}. "
                "MSC write did not commit; unplug/replug and retry."
            )
    print(f"firmware digest ok ({expected})")


def _copy_firmware_tree(dest: Path) -> None:
    """Recursively copy firmware sources including lib/adafruit_hid."""
    dest.mkdir(parents=True, exist_ok=True)
    for path in FIRMWARE_SRC.rglob("*"):
        if not path.is_file():
            continue
        rel = path.relative_to(FIRMWARE_SRC)
        target = dest / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(path, target)
        print(f"copied {rel.as_posix()} → {target}")


def _flush_circuitpy(mount: Path) -> None:
    """Push FAT writes through the host page cache."""
    try:
        for name in (*DIGEST_FILES, STAMP_NAME):
            path = mount / name
            if not path.is_file():
                continue
            fd = os.open(path, os.O_RDONLY)
            try:
                os.fsync(fd)
            finally:
                os.close(fd)
        os.sync()
    except OSError as exc:
        print(f"CIRCUITPY flush warning: {exc}")


def clean_circuitpy_junk(mount: Path) -> None:
    """Remove desktop indexer/trash dirs that force CircuitPython auto-reload."""
    for name in CIRCUITPY_JUNK:
        path = mount / name
        if not path.exists():
            continue
        try:
            if path.is_dir():
                shutil.rmtree(path, ignore_errors=True)
            else:
                path.unlink()
            print(f"removed junk {name}")
        except OSError as exc:
            print(f"junk cleanup warning {name}: {exc}")


def circuitpy_block_device(mount: Path) -> Path | None:
    """Return the block device backing the CIRCUITPY mount (e.g. /dev/sdd1)."""
    try:
        out = subprocess.check_output(
            ["findmnt", "-n", "-o", "SOURCE", "--target", str(mount)],
            text=True,
            stderr=subprocess.DEVNULL,
        ).strip()
    except (FileNotFoundError, subprocess.CalledProcessError):
        return None
    if not out:
        return None
    return Path(out.split()[0])


def unmount_circuitpy(mount: Path) -> None:
    """Eject CIRCUITPY so USB MSC commits host writes into Pico flash."""
    source = circuitpy_block_device(mount)
    if source is None:
        raise RuntimeError(f"cannot find block device for {mount}")
    result = subprocess.run(
        ["udisksctl", "unmount", "-b", str(source)],
        capture_output=True,
        text=True,
    )
    if result.returncode == 0:
        print(f"unmounted {source} ({mount})")
        return
    result2 = subprocess.run(
        ["umount", str(mount)],
        capture_output=True,
        text=True,
    )
    if result2.returncode != 0:
        detail = (result.stderr or result.stdout or result2.stderr or "").strip()
        raise RuntimeError(
            f"failed to unmount {mount} ({source}): {detail or 'umount failed'}"
        )
    print(f"unmounted {mount} via umount")


def wait_circuitpy_mount(timeout: float = 20.0) -> Path:
    """Wait until CIRCUITPY reappears after MCU reset / remount."""
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        mount = probe.circuitpy_mount()
        if mount is not None and (mount / "code.py").is_file():
            return mount
        time.sleep(0.4)
    raise SystemExit(
        "CIRCUITPY did not remount after deploy. "
        "Unplug/replug once if the volume stays missing."
    )


def reload_after_deploy(mount: Path, *, expected_digest: str) -> None:
    """Flush → eject → MCU reset → verify running digest (hands-free)."""
    _flush_circuitpy(mount)
    try:
        print("ejecting CIRCUITPY so the Pico commits host writes…")
        unmount_circuitpy(mount)
    except (RuntimeError, OSError) as exc:
        raise SystemExit(
            f"eject failed ({exc}). "
            "Close anything using CIRCUITPY, then re-run make firmware."
        ) from exc
    time.sleep(0.4)
    try:
        print("MCU soft-reset (re-reads flash; runs boot.py + code.py)…")
        port, banner = soft_reset_pico(expected_digest=expected_digest)
        print(f"soft-reset ok ({port})")
    except SystemExit:
        raise
    except (OSError, TimeoutError, RuntimeError) as exc:
        raise SystemExit(
            f"soft-reset/verify failed ({exc}). "
            "Close tio (killall tio) and re-run make firmware, "
            "or unplug/replug once."
        ) from exc
    remount = wait_circuitpy_mount()
    print(f"CIRCUITPY remounted at {remount}")
    verify_running_digest(expected=expected_digest, banner=banner, mount=remount)


def prepare_firmware_tree() -> str:
    """Write deploy_stamp.py from current boot/code/keymap; return digest."""
    digest = firmware_tree_digest(FIRMWARE_SRC)
    write_deploy_stamp(FIRMWARE_SRC, digest)
    return digest


def deploy(board: dict) -> None:
    """Copy CircuitPython app to CIRCUITPY and MCU-reset (digest-gated).

    CIRCUITPY app deploy no longer needs OPERATOR_FLASH — that flag remains for
    UF2 / picotool loads only. OPERATOR_VERIFY + present pass still gate HWIL.
    """
    board_id = board["id"]
    assent.require_verify(f"firmware write for {board_id}")
    if not stage_passed(board_id, "present"):
        raise SystemExit(
            f"{board_id} present stage has not passed. "
            f"Next: OPERATOR_VERIFY=1 make stage BOARD={board_id} STAGE=present"
        )

    if not adafruit_hid_present(FIRMWARE_SRC):
        raise SystemExit(
            f"firmware source missing {FIRMWARE_SRC / ADAFRUIT_HID_REL}. "
            "Restore the vendored Adafruit HID package before deploy."
        )

    digest = prepare_firmware_tree()
    print(f"firmware digest {digest}")

    if probe.is_sim():
        dest = Path("/tmp/IR_GATEWAY_SIM_CIRCUITPY")
        if dest.exists():
            shutil.rmtree(dest)
        _copy_firmware_tree(dest)
        require_adafruit_hid(dest)
        print(f"sim deploy: copied firmware to {dest}")
        return

    mount = probe.circuitpy_mount()
    if mount is None:
        raise SystemExit(
            "CIRCUITPY volume not mounted. "
            "Next: OPERATOR_VERIFY=1 make firmware. "
            "Re-run present when the USB identity to record has changed. "
            f"Expected sources in {FIRMWARE_SRC}"
        )
    clean_circuitpy_junk(mount)
    _copy_firmware_tree(mount)
    require_adafruit_hid(mount)
    print("CIRCUITPY copied; committing and reloading Pico…")
    reload_after_deploy(mount, expected_digest=digest)
    print("firmware deploy complete")


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description="Deploy Pico CircuitPython firmware")
    parser.add_argument("--board", default="pico")
    args = parser.parse_args(argv)
    board = load_board(args.board)
    deploy(board)


if __name__ == "__main__":
    main()
